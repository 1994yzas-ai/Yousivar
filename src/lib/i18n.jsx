dict.en = { ...dict.en, ...providerDict.en, ...chatDict.en };
dict.ar = { ...dict.ar, ...providerDict.ar, ...chatDict.ar };

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const saved = localStorage.getItem('ysv.lang');
    if (saved === 'ar' || saved === 'en') return saved;
    return navigator.language && navigator.language.toLowerCase().startsWith('ar') ? 'ar' : 'en';
  });

  useEffect(() => {
    localStorage.setItem('ysv.lang', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }, [lang]);

  const value = useMemo(() => {
    const t = (key) => dict[lang]?.[key] ?? dict.en[key] ?? key;
    return {
      lang,
      setLang,
      dir: lang === 'ar' ? 'rtl' : 'ltr',
      isRTL: lang === 'ar',
      toggle: () => setLang(lang === 'ar' ? 'en' : 'ar'),
      t,
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}